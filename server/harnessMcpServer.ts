/**
 * Lyra Harness MCP (Model Context Protocol) Server
 * 
 * Exposes Lyra's Cloud Swarm & Autonomous Execution Engine to external harnesses
 * (Antigravity, OpenAI Codex, Claude Code, Cursor, etc.) via standardized MCP tools.
 */

